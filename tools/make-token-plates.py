#!/usr/bin/env python3
"""make-token-plates.py — full-body transparent plates for the table, in batches.

A token on the map wants the whole figure on a transparent field. The portraits
stay what they are (the article's picture); the plate is a second file,
`portraits/player/fullbody/<id>.png`, wired as `fullBody` on the article, and
the sheet builder puts it on the prototype token (`token_of()`).

The batch is a pipeline; a grid is one way to feed it. One figure per render
is the quality path (the lead as reference keeps the likeness, ~1024 px a
figure); an RxC sheet trades that for count (a 3x3 at 1024 px is ~340 px a
figure and the generator must keep ten likenesses straight at once) — right
for background NPCs and the roster toads, wrong for the party. The tool here
renders one subject per image, so `plan --grid` exists for a generator that
does not: it writes one prompt per sheet, and `cut --grid-sheet` slices and
keys what comes back.

  plan    which sheet characters are READY / CUT (a flat field to key) /
          GENERATE (needs a render), in table-use order, and a manifest of
          prompts built from the article (look from the appearance captions,
          the lead as the reference image, a key colour the character does not
          wear).
  cut     key a render (or an opaque plate on a flat field) into a trimmed,
          square, transparent PNG — magenta / green chroma or the border colour.
  apply   write `fullBody` + `fullBodyCaption` for every plate on disk that the
          article does not point at yet (characters.json round-trips as is).
  check   every `fullBody` is a real transparent plate (alpha border, >= MIN_PX);
          `--check` exits 1 otherwise.
  pixel   a pixel-art sprite (the Bone-Line cast): keep the figure, drop the burnt-in name under it,
          scale by whole pixels to >= 640 px — pixel art is regenerated by nobody.
  render  the hands-off loop: for every sheet character still without a plate, in table-use order,
          pad the reference onto a key-colour canvas, send prompt + reference to the local ComfyUI
          (a Comfy Desktop instance or classic install on :8188, the legacy app on :8000; Qwen-Image-2.1 when the server has
          it — native alpha — else Qwen-Image-Edit; your own exported API-format workflow with --workflow),
          wait, cut, QC (keyed field, clear border, nothing cropped), retry with a new seed, apply,
          next. Resumable: a plate on disk is skipped. Ctrl-C between characters is safe. The prompt, the
          canvas and the QC follow the character's body plan (`bodyPlan` on the article, else the race line):
          only a biped is asked for legs and feet — a Toad stays short, a Boo floats, a flower keeps its stem.
          --full is the hands-off run: every tier, the best attempt kept when none passes QC (flagged
          "needs eyes" in the caption + log), the reference-less drawn from the record on a 2.1 server,
          a contact sheet at the end; review in git, `drop` the bad ones, re-render them with --ids --redo.
  drop    take plates back out (file + fullBody wiring) — the undo for a plate that failed the eye.
  heal    re-check every chroma-keyed plate on disk pixel by pixel against its key colour and give back
          the figure pixels an earlier keyer (int16 overflow, before 2026-10-05) punched out — specks
          in dark purples / blues / reds. Idempotent; `check` reports plates that still need it.
  sheet   a contact sheet of plates for the eyeball pass.

  python3 tools/make-token-plates.py plan [--manifest /tmp/plates/manifest.json] [--tier 1]
  python3 tools/make-token-plates.py plan --grid 3 3 --manifest grids.json   # one prompt per 3x3 sheet, for a generator that draws grids
  python3 tools/make-token-plates.py cut  --grid-sheet grid-01.png --rows 3 --cols 3 --ids a b c d e f g h i   # slice + key a rendered sheet
  python3 tools/make-token-plates.py cut  --id waluigi --src /tmp/plates/raw/waluigi.png [--key magenta|green|auto]
  python3 tools/make-token-plates.py cut  --flat                 # key every opaque plate whose field is flat
  python3 tools/make-token-plates.py cut  --raw-dir ~/renders    # every <id>.png rendered elsewhere from the manifest
  python3 tools/make-token-plates.py render                      # drive the local ComfyUI (Qwen-Image-2.1 in Comfy Desktop) through everything left
  python3 tools/make-token-plates.py render --workflow my_qwen_edit_api.json --tier 2 --limit 20
  python3 tools/make-token-plates.py render --full               # everything, hands-off (start.bat plates); then: git status, drop the bad ones
  python3 tools/make-token-plates.py drop --ids kyrn pet_rock     # undo two plates the eye rejected
  python3 tools/token-plate-studio.py                            # the same loop with eyes on it: preview, crop, key, remove background, accept
  python3 tools/make-token-plates.py apply [--date 2026-10-05]
  python3 tools/make-token-plates.py check
  python3 tools/make-token-plates.py sheet --out /tmp/plates/sheet.jpg [--ids a b c]

Needs Pillow + numpy (+ scipy for a fast flood fill; falls back without).
"""
