class Comfy:
    """The little HTTP the ComfyUI server speaks (urllib only, so it runs where start.py runs)."""

    def __init__(self, url=None):
        self.url = (url or COMFY_URL or "http://127.0.0.1:%d" % COMFY_PORTS[0]).rstrip("/")
        import uuid
        self.client = uuid.uuid4().hex

    @classmethod
    def discover(cls, url=None):
        """The server to talk to: the one given, else the first of COMFY_PORTS that answers."""
        if url or COMFY_URL:
            return cls(url or COMFY_URL)
        for port in COMFY_PORTS:
            c = cls("http://127.0.0.1:%d" % port)
            if c.alive():
                return c
        return cls("http://127.0.0.1:%d" % COMFY_PORTS[0])

    def engine(self):
        """Which builtin graph this server can run: qwen21 (Qwen-Image-2.1), qwen-edit (Qwen-Image-Edit), or None."""
        for name, (node, _, _) in ENGINES.items():
            if self.has_node(node):
                return name
        return None

    def choices(self, class_type, field):
        """The files a loader node offers (the server's own model folders)."""
        try:
            info = self._json("/object_info/" + class_type)[class_type]["input"]["required"][field][0]
            return list(info) if isinstance(info, list) else []
        except Exception:  # noqa: BLE001
            return []

    def run(self, workflow, dst, timeout=900):
        """Queue, wait, download — one image."""
        pid = self.queue(workflow)
        return self.download(self.wait(pid, timeout=timeout), dst)

    def _json(self, path, data=None, method=None):
        import urllib.error
        import urllib.request
        body = json.dumps(data).encode("utf-8") if data is not None else None
        req = urllib.request.Request(self.url + path, data=body, method=method or ("POST" if body else "GET"),
                                     headers={"Content-Type": "application/json"} if body else {})
        try:
            with urllib.request.urlopen(req, timeout=60) as r:
                raw = r.read()
        except urllib.error.HTTPError as exc:
            # ComfyUI answers a bad graph with 400 + JSON that names the node and the field: say that, not "Bad Request"
            detail = exc.read().decode("utf-8", "replace")[:1500]
            try:
                j = json.loads(detail)
                msgs = [j.get("error", {}).get("message") if isinstance(j.get("error"), dict) else j.get("error")]
                for node, err in (j.get("node_errors") or {}).items():
                    for e in err.get("errors", []):
                        msgs.append(f"node {node} ({err.get('class_type', '?')}): {e.get('message')} {e.get('details', '')}".strip())
                detail = "; ".join(m for m in msgs if m)
            except ValueError:
                pass
            raise RuntimeError(f"ComfyUI rejected the request ({exc.code}): {detail}") from None
        return json.loads(raw.decode("utf-8")) if raw else {}

    def alive(self):
        try:
            self._json("/system_stats")
            return True
        except Exception:  # noqa: BLE001
            return False

    def has_node(self, class_type):
        try:
            return class_type in self._json("/object_info/" + class_type)
        except Exception:  # noqa: BLE001
            return False

    def upload(self, path, name):
        import urllib.request
        boundary = "----waluipedia%s" % self.client
        data = open(path, "rb").read()
        parts = []
        for field, value in (("type", "input"), ("overwrite", "true"), ("subfolder", "token-plates")):
            parts.append(("--%s\r\nContent-Disposition: form-data; name=\"%s\"\r\n\r\n%s\r\n" % (boundary, field, value)).encode())
        parts.append(("--%s\r\nContent-Disposition: form-data; name=\"image\"; filename=\"%s\"\r\nContent-Type: image/png\r\n\r\n" % (boundary, name)).encode())
        parts.append(data)
        parts.append(("\r\n--%s--\r\n" % boundary).encode())
        req = urllib.request.Request(self.url + "/upload/image", data=b"".join(parts), method="POST",
                                     headers={"Content-Type": "multipart/form-data; boundary=" + boundary})
        with urllib.request.urlopen(req, timeout=120) as r:
            info = json.loads(r.read().decode("utf-8"))
        sub = info.get("subfolder") or ""
        return (sub + "/" if sub else "") + info["name"]

    def queue(self, workflow):
        out = self._json("/prompt", {"prompt": workflow, "client_id": self.client})
        if out.get("node_errors"):
            raise RuntimeError("ComfyUI rejected the workflow: %s" % json.dumps(out["node_errors"])[:800])
        return out["prompt_id"]

    def wait(self, prompt_id, timeout=900, poll=2.0):
        import time
        t0 = time.time()
        while time.time() - t0 < timeout:
            hist = self._json("/history/" + prompt_id).get(prompt_id)
            if hist:
                status = hist.get("status") or {}
                if status.get("status_str") == "error":
                    raise RuntimeError("ComfyUI reported an error: %s" % json.dumps(status.get("messages", []))[:800])
                if hist.get("outputs"):
                    return hist["outputs"]
            time.sleep(poll)
        raise TimeoutError("ComfyUI did not finish %s in %ds" % (prompt_id, timeout))

    def download(self, outputs, dst):
        import urllib.parse
        import urllib.request
        for node in outputs.values():
            for im in node.get("images", []):
                if im.get("type") not in (None, "output"):
                    continue
                q = urllib.parse.urlencode({"filename": im["filename"], "subfolder": im.get("subfolder", ""), "type": "output"})
                with urllib.request.urlopen(self.url + "/view?" + q, timeout=120) as r:
                    open(dst, "wb").write(r.read())
                return dst
        raise RuntimeError("the workflow produced no output image (is there a SaveImage node?)")


def workflow_fill(wf, prompt, image_name, prefix, seed, negative=NEGATIVE):
    """Fill an API-format workflow: the sampler's positive prompt, its negative, every LoadImage, the SaveImage prefix, the seed."""
    wf = json.loads(json.dumps(wf))
    samplers = [k for k, v in wf.items() if v.get("class_type") in SAMPLERS]
    if not samplers:
        raise SystemExit("render: no KSampler in the workflow — export the API format of a workflow that samples")
    for sid in samplers:
        inp = wf[sid]["inputs"]
        for field in ("seed", "noise_seed"):
            if field in inp:
                inp[field] = seed
        for role, text in (("positive", prompt), ("negative", negative)):
            link = inp.get(role)
            if isinstance(link, list):
                node = wf.get(str(link[0]), {})
                fields = ("negative_prompt",) if role == "negative" and "negative_prompt" in node.get("inputs", {}) else PROMPT_FIELDS
                for f in fields:
                    if f in node.get("inputs", {}):
                        node["inputs"][f] = text
    for v in wf.values():
        if v.get("class_type") == "LoadImage":
            v["inputs"]["image"] = image_name
        if v.get("class_type") == "SaveImage":
            v["inputs"]["filename_prefix"] = prefix
    return wf


def workflow_tune(wf, steps=None, resolution=None, cfg=None, models=None, engine=None, cache=True):
    """Dial a builtin graph: sampler steps / cfg, the 2.1 reference budget, loader filenames, the optional cache node."""
    wf = json.loads(json.dumps(wf))
    for v in wf.values():
        if v.get("class_type") in SAMPLERS:
            if steps:
                v["inputs"]["steps"] = int(steps)
            if cfg is not None:
                v["inputs"]["cfg"] = float(cfg)
        if v.get("class_type") == "TextEncodeQwenImage21" and resolution is not None:
            v["inputs"]["resolution"] = int(resolution)
    if models and engine in ENGINES:
        ids = ENGINES[engine][2]
        for key, field in (("unet", "unet_name"), ("clip", "clip_name"), ("vae", "vae_name")):
            if models.get(key):
                wf[ids[key]]["inputs"][field] = models[key]
    if not cache and "469" in wf and wf["469"].get("class_type") == "QwenImage21Cache":
        src = wf["469"]["inputs"]["model"]
        del wf["469"]
        for v in wf.values():
            if v.get("inputs", {}).get("model") == ["469", 0]:
                v["inputs"]["model"] = src
    return wf


def qwen21_t2i_prompt(art, transparent=True):
    """No usable reference: 2.1 draws the figure from the record (name, title, race, the look line). Flagged in the
    log and the caption, because nothing anchors the face."""
    name = art.get("name", art["id"])
    title = (art.get("title") or "").strip()
    race = re.split(r"[;.]", (art.get("race") or "").strip())[0].strip()
    if re.match(r"^(unknown|unfiled|corrupted copy)\b", race, re.I) and " — " in race:
        race = race.split(" — ", 1)[1].strip()
    elif re.match(r"^(unknown|unfiled)\b", race, re.I):
        race = ""
    who = name + (f", {title}" if title and title.lower() not in name.lower() else "") + (f" ({race})" if race else "")
    look = look_of(art)
    plan, build = body_plan_of(art)
    body = f"A full-body character illustration of {who}. "
    if look:
        body += f"{look}. "
    body += (f"The whole figure, nothing cropped, built exactly the way this character is built: {build}. "
             "Facing the viewer and turned slightly, holding their weapon or tool if they carry one"
             + ("; no legs, feet or human proportions the character does not have. " if plan != "biped" else ". ")
             + "Painterly illustration with clean edges. One figure only, centred, "
             "with empty space on every side; no floor, no cast shadow, no scenery, no text, no border. ")
    body += ("Transparent background: output a PNG image with an alpha channel and nothing behind the figure." if transparent
             else "The entire background is plain solid flat bright magenta.")
    return body


def prep_reference(src, dst, key, full_body, size=(1024, 1024), plan="biped"):
    """The reference the edit model sees: the figure on a key-colour canvas — a full-body plate with a margin, a
    bust in the upper part with empty key colour below it, which is where the rest of the body gets drawn. The
    canvas is also the edit's output size (2.1 samples at the first reference's size): portrait for a standing
    biped, square for every other build (plan_canvas), and the bust sits lower and larger the less body there is
    to add (PLAN_BUST) — a Boo's "bust" is the whole Boo."""
    from PIL import Image
    kc = KEYS[key]
    im = Image.open(src).convert("RGBA")
    w, h = size
    canvas = Image.new("RGBA", (w, h), kc + (255,))
    if full_body:
        im = fit(im, int(w * 0.86), int(h * 0.88))
        canvas.paste(im, ((w - im.width) // 2, (h - im.height) // 2), im)
    else:
        bw, bh, top = PLAN_BUST.get(plan, PLAN_BUST_DEFAULT)
        im = fit(im, int(w * bw), int(h * bh))
        canvas.paste(im, ((w - im.width) // 2, int(h * top)), im)
    canvas.convert("RGB").save(dst)
    return dst


def fit(im, bw, bh, up_to=3.0):
    """Scale the reference into a box — down, or UP to three times (thumbnail() only shrinks, so a 268 px lead sat
    as a speck at the top of a 1216 px canvas with a page of empty field under it to fill with body)."""
    from PIL import Image
    scale = min(bw / im.width, bh / im.height, up_to)
    if abs(scale - 1) < 1e-6:
        return im
    return im.resize((max(1, round(im.width * scale)), max(1, round(im.height * scale))), Image.LANCZOS)


def qwen21_prompt(entry, full_body, transparent=True):
    """The 2.1 instruction: the reference is <image1>; ask for the PNG with alpha the model can draw natively."""
