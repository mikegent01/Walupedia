PIXEL_MAX_PX = 260
PIXEL_TARGET = 640


def is_pixel_art(path):
    from PIL import Image
    im = Image.open(path)
    if max(im.size) > PIXEL_MAX_PX:
        return False
    colours = im.convert("RGBA").getcolors(4096)
    return colours is not None and len(colours) <= 1024


def pixel_plate(src, dst):
    """Crop a pixel sprite to its tallest block of content (the figure; the label under it goes), scale by whole pixels."""
    from PIL import Image
    np = _np()
    im = Image.open(src).convert("RGBA")
    arr = np.asarray(im).copy()
    a = arr[:, :, 3] > 0
    try:  # stray marks (an apostrophe, a lost pixel) are not the figure
        from scipy import ndimage
        lab, n = ndimage.label(a)
        sizes = ndimage.sum(a, lab, range(1, n + 1))
        main = int(np.argmax(sizes)) + 1
        cols_main = np.where((lab == main).any(axis=0))[0]
        c0, c1 = cols_main[0] - 4, cols_main[-1] + 4
        for i, sz in enumerate(sizes, 1):
            cols_i = np.where((lab == i).any(axis=0))[0]
            if sz < 6 or cols_i[-1] < c0 or cols_i[0] > c1:   # a lost pixel, or a glyph beside the figure
                arr[lab == i] = 0
        a = arr[:, :, 3] > 0
        im = Image.fromarray(arr, "RGBA")
    except ImportError:
        pass
    widths = a.sum(axis=1)
    rows = np.where(widths > 3)[0]          # a row with <= 3 lit pixels is a gap (or the thread of a stray glyph)
    if not len(rows):
        raise SystemExit(f"pixel: {src} is empty")
    blocks, start, prev = [], rows[0], rows[0]
    for r in rows[1:]:
        if r - prev > 2:
            blocks.append((start, prev)); start = r
        prev = r
    blocks.append((start, prev))
    top, bottom = max(blocks, key=lambda b: b[1] - b[0])
    sub = a[top:bottom + 1]
    cols = np.where(sub.max(axis=0) > 0)[0]
    fig = im.crop((int(cols[0]), int(top), int(cols[-1]) + 1, int(bottom) + 1))
    k = max(1, -(-PIXEL_TARGET // max(fig.size)))
    fig = fig.resize((fig.width * k, fig.height * k), Image.NEAREST)
    side = int(max(fig.size) * (1 + 2 * MARGIN))
    canvas = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    canvas.paste(fig, ((side - fig.width) // 2, (side - fig.height) // 2))
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    canvas.save(dst, optimize=True)
    return k, fig.size, len(blocks) - 1


