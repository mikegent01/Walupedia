def statuses(arts, by_sheet):
    """One dict per sheet character: id, tier, status (READY / CUT / GENERATE), details."""
    use = usage_counts()
    out = []
    for a in arts:
        s = by_sheet.get(a["id"])
        if not s:
            continue
        fb = (a.get("fullBody") or "").replace("\\", "/")
        lead = (a.get("image") or "").replace("\\", "/")
